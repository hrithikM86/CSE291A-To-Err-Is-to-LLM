"""Export this new baseline for inspection/PM curation, without any model calls."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parent


def make_export(study, output, project=ROOT):
    state = json.loads((study / 'study.json').read_text())
    if state.get('schema_version') != 'mixed-baseline-study/v1':
        raise ValueError('Select a study generated by this baseline-only runner.')
    if output.exists():
        raise ValueError(f'Export already exists: {output}')
    tasks = []
    files = {}
    for name in ['study.json', 'totals.json', 'results.csv', 'checks.csv',
                 'calls.csv', 'lineage_edges.csv', 'lineage_summary.csv', 'console.log', 'metagpt.log']:
        path = study / name
        if path.is_file():
            files[Path('study') / name] = path
    dataset = project / 'data/HumanEval.jsonl'
    files[Path('data/HumanEval.jsonl')] = dataset
    for name in ['run_baseline.py', 'role_lineage.py', 'export_baseline.py',
                 'lineage.py', 'metagpt_clean.py', 'runtime_utils.py',
                 'check_suites.py', 'evaluate_humaneval.py']:
        files[Path('code') / name] = project / name
    for index in state['indices']:
        task_id = f'HumanEval/{index}'
        attempts = state['tasks'].get(task_id, [])
        record = dict(task_id=task_id, status='not_attempted')
        if attempts:
            attempt = max(attempts, key=lambda a: a['attempt'])
            source = (study / attempt['folder']).resolve()
            if not source.is_relative_to(study.resolve()):
                raise ValueError('Attempt folder escapes study directory.')
            record.update(attempt=attempt['attempt'], status=attempt['status'], folder=attempt['folder'])
            for path in source.rglob('*'):
                if path.is_file() and path.suffix in {'.json', '.txt', '.py', '.log'}:
                    files[Path('tasks') / Path(attempt['folder']) / path.relative_to(source)] = path
        tasks.append(record)
        test = project / f'tests/HumanEval_{index}.json'
        files[Path('tests') / test.name] = test
    manifest = dict(schema_version='mixed-baseline-export/v1', source_study=study.name,
                    status=state['status'], tasks=tasks,
                    note='Latest attempts only; partial/missing results are explicitly identified.',
                    sha256={str(name): hashlib.sha256(path.read_bytes()).hexdigest()
                            for name, path in files.items()})
    output.parent.mkdir(parents=True, exist_ok=True)
    # A failed export must not leave an apparently complete ZIP at the final name.
    temporary = output.with_suffix('.zip.tmp')
    try:
        with zipfile.ZipFile(temporary, 'w', zipfile.ZIP_DEFLATED) as archive:
            archive.writestr('manifest.json', json.dumps(manifest, indent=2))
            for name, path in files.items():
                archive.write(path, name)
        temporary.replace(output)
    finally:
        if temporary.exists():
            temporary.unlink()
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('study', type=Path)
    args = parser.parse_args()
    study = args.study.resolve()
    path = ROOT / 'exports' / ('baseline-export-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ') + '.zip')
    manifest = make_export(study, path)
    print('Exported tasks:', len(manifest['tasks']))
    print('Study status:', manifest['status'])
    print('Upload this ZIP:', path)


if __name__ == '__main__':
    main()
